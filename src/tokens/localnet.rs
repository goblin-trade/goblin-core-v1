pub enum Token {
    BaseToken,
    QuoteToken,
}

impl Token {
    pub const fn address(&self) -> [u8; 20] {
        match self {
            // Base token: 0xe1080224B632A93951A7CFA33EeEa9Fd81558b5e
            Token::BaseToken => [
                0xe1, 0x08, 0x02, 0x24, 0xb6, 0x32, 0xa9, 0x39, 0x51, 0xa7, 0xcf, 0xa3, 0x3e, 0xee,
                0xa9, 0xfd, 0x81, 0x55, 0x8b, 0x5e,
            ],
            // Quote token: 0x3f1Eae7D46d88F08fc2F8ed27FCb2AB183EB2d0E
            Token::QuoteToken => [
                0x3f, 0x1e, 0xae, 0x7d, 0x46, 0xd8, 0x8f, 0x08, 0xfc, 0x2f, 0x8e, 0xd2, 0x7f, 0xcb,
                0x2a, 0xb1, 0x83, 0xeb, 0x2d, 0x0e,
            ],
        }
    }
}

pub const HARDCODED_TOKENS: [[u8; 20]; 2] =
    [Token::BaseToken.address(), Token::QuoteToken.address()];
